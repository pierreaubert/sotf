    #[test]
    fn test_bem_config_default() {
        let config = BEMConfig::default();
        assert_eq!(config.freq_min, 100.0);
        assert_eq!(config.freq_max, 20000.0);
        assert_eq!(config.speed_of_sound, 343.0);
    }

    #[test]
    fn test_time_estimation() {
        // Small simulation: 10 sources, 100 freqs, 500 vertices
        let time_small = estimate_bem_time(10, 100, 500);
        assert!(time_small < 1.0); // Less than 1 hour

        // Large simulation: 1000 sources, 512 freqs, 5000 vertices
        let time_large = estimate_bem_time(1000, 512, 5000);
        assert!(time_large > 10.0); // More than 10 hours
    }

    #[test]
    fn test_bem_availability() {
        // This will fail unless MESH2HRTF is installed
        let available = is_bem_available();
        println!("BEM solver available: {}", available);
    }
