//! BEM (Boundary Element Method) solver integration
//!
//! This module provides integration with external BEM solvers for high-accuracy HRTF simulation.
//!
//! # Supported BEM Solvers
//!
//! ## MESH2HRTF
//! - Open-source BEM solver specifically for HRTF computation
//! - Website: https://mesh2hrtf.org/
//! - Input: Triangle mesh + source/receiver positions
//! - Output: Frequency-domain transfer functions
//!
//! ## Integration Workflow
//! 1. Export mesh to BEM-compatible format (Wavefront OBJ or custom)
//! 2. Generate BEM configuration file
//! 3. Run BEM solver (external process)
//! 4. Import results and convert to time-domain impulse responses
//! 5. Write to SOFA format

use crate::acoustics::model::AcousticHeadModel;
use crate::error::{ScannerError, ScannerResult};
use crate::mesh::Mesh;
use nalgebra::Point3;
use std::path::{Path, PathBuf};
use std::process::Command;

/// BEM solver configuration
#[derive(Debug, Clone)]
pub struct BEMConfig {
    /// Path to BEM solver executable
    pub solver_path: PathBuf,

    /// Frequency range for simulation (Hz)
    pub freq_min: f32,
    pub freq_max: f32,

    /// Number of frequency points
    pub num_frequencies: usize,

    /// Speed of sound (m/s)
    pub speed_of_sound: f32,

    /// Mesh refinement level (higher = more accurate but slower)
    pub refinement_level: u8,
}

impl Default for BEMConfig {
    fn default() -> Self {
        Self {
            solver_path: PathBuf::from("mesh2hrtf"),
            freq_min: 100.0,          // 100 Hz
            freq_max: 20000.0,        // 20 kHz
            num_frequencies: 512,
            speed_of_sound: 343.0,    // m/s at 20°C
            refinement_level: 1,
        }
    }
}

/// BEM solver interface
pub struct BEMSolver {
    config: BEMConfig,
}

impl BEMSolver {
    /// Create a new BEM solver
    pub fn new(config: BEMConfig) -> Self {
        Self { config }
    }

    /// Export mesh to BEM-compatible format
    ///
    /// Exports to Wavefront OBJ format with specific requirements for BEM:
    /// - All faces must be triangles
    /// - Mesh must be closed (watertight)
    /// - Normals pointing outward
    pub fn export_mesh_for_bem(&self, mesh: &Mesh, output_path: &Path) -> ScannerResult<()> {
        log::info!("Exporting mesh for BEM solver: {:?}", output_path);

        // Validate mesh is suitable for BEM
        self.validate_mesh_for_bem(mesh)?;

        // Export to OBJ format
        mesh.export_obj(output_path.to_str().unwrap())?;

        log::info!("✓ Mesh exported for BEM");
        Ok(())
    }

    /// Validate that mesh meets BEM requirements
    fn validate_mesh_for_bem(&self, mesh: &Mesh) -> ScannerResult<()> {
        // Check minimum vertex count
        if mesh.vertex_count() < 100 {
            return Err(ScannerError::InvalidConfig(
                "Mesh too coarse for BEM (need at least 100 vertices)".to_string(),
            ));
        }

        // Note: Additional validation would check:
        // - Mesh is closed (no holes)
        // - All normals point outward
        // - No degenerate triangles
        // These checks are complex and omitted here for brevity

        log::info!(
            "Mesh validation: {} vertices, {} triangles",
            mesh.vertex_count(),
            mesh.triangle_count()
        );

        Ok(())
    }

    /// Generate BEM configuration file
    ///
    /// Creates a configuration file for the BEM solver with:
    /// - Mesh path
    /// - Source positions
    /// - Receiver positions (ears)
    /// - Frequency range
    pub fn generate_bem_config(
        &self,
        model: &AcousticHeadModel,
        source_positions: &[Point3<f32>],
        output_path: &Path,
    ) -> ScannerResult<()> {
        log::info!("Generating BEM configuration: {:?}", output_path);

        // Generate MESH2HRTF-compatible configuration
        let config_content = self.create_mesh2hrtf_config(model, source_positions);

        std::fs::write(output_path, config_content)
            .map_err(|e| ScannerError::Io(format!("Failed to write BEM config: {}", e)))?;

        log::info!("✓ BEM configuration generated");
        Ok(())
    }

    /// Create MESH2HRTF configuration content
    fn create_mesh2hrtf_config(
        &self,
        model: &AcousticHeadModel,
        source_positions: &[Point3<f32>],
    ) -> String {
        let mut config = String::new();

        // Header
        config.push_str("# MESH2HRTF Configuration\n");
        config.push_str("# Generated by head-scanner\n\n");

        // Frequency settings
        config.push_str(&format!(
            "frequencyRange {} {} {}\n",
            self.config.freq_min, self.config.freq_max, self.config.num_frequencies
        ));

        // Speed of sound
        config.push_str(&format!("speedOfSound {}\n", self.config.speed_of_sound));

        // Mesh refinement
        config.push_str(&format!("refinement {}\n", self.config.refinement_level));

        // Receiver positions (ears) - relative to head center
        config.push_str("\n# Receiver positions (ears)\n");
        let left_rel = model.left_ear - model.head_center;
        let right_rel = model.right_ear - model.head_center;

        config.push_str(&format!(
            "receiver 0 {} {} {}\n",
            left_rel.x / 100.0,
            left_rel.y / 100.0,
            left_rel.z / 100.0
        ));
        config.push_str(&format!(
            "receiver 1 {} {} {}\n",
            right_rel.x / 100.0,
            right_rel.y / 100.0,
            right_rel.z / 100.0
        ));

        // Source positions
        config.push_str("\n# Source positions\n");
        for (i, pos) in source_positions.iter().enumerate() {
            let rel = pos - model.head_center;
            config.push_str(&format!(
                "source {} {} {} {}\n",
                i,
                rel.x / 100.0,
                rel.y / 100.0,
                rel.z / 100.0
            ));
        }

        config
    }

    /// Run BEM solver (external process)
    ///
    /// This launches the BEM solver as an external process.
    /// **Note**: This can take hours for full HRTF computation!
    pub fn run_bem_simulation(
        &self,
        mesh_path: &Path,
        config_path: &Path,
        output_dir: &Path,
    ) -> ScannerResult<()> {
        log::info!("Starting BEM simulation...");
        log::warn!(
            "BEM simulation can take several hours. Consider running overnight."
        );

        // Check if solver exists
        if !self.config.solver_path.exists() {
            return Err(ScannerError::InvalidConfig(format!(
                "BEM solver not found: {:?}\nInstall MESH2HRTF from https://mesh2hrtf.org/",
                self.config.solver_path
            )));
        }

        // Run BEM solver
        let output = Command::new(&self.config.solver_path)
            .arg("--mesh")
            .arg(mesh_path)
            .arg("--config")
            .arg(config_path)
            .arg("--output")
            .arg(output_dir)
            .output()
            .map_err(|e| {
                ScannerError::Io(format!("Failed to execute BEM solver: {}", e))
            })?;

        if !output.status.success() {
            let stderr = String::from_utf8_lossy(&output.stderr);
            return Err(ScannerError::InvalidConfig(format!(
                "BEM simulation failed:\n{}",
                stderr
            )));
        }

        log::info!("✓ BEM simulation completed");
        Ok(())
    }

    /// Import BEM results and convert to impulse responses
    ///
    /// BEM solvers typically output frequency-domain data.
    /// This function:
    /// 1. Reads frequency-domain transfer functions
    /// 2. Applies inverse FFT to get time-domain impulse responses
    /// 3. Resamples to target sample rate if needed
    pub fn import_bem_results(
        &self,
        bem_output_dir: &Path,
        target_sample_rate: f32,
    ) -> ScannerResult<(Vec<Point3<f32>>, Vec<Vec<Vec<f32>>>)> {
        log::info!("Importing BEM results from {:?}", bem_output_dir);

        // Look for output files
        // MESH2HRTF typically creates:
        // - ObjectMesh_hrtf.nc (NetCDF format)
        // - or individual .txt files per source/receiver

        let hrtf_file = bem_output_dir.join("ObjectMesh_hrtf.nc");

        if !hrtf_file.exists() {
            return Err(ScannerError::InvalidConfig(format!(
                "BEM output file not found: {:?}",
                hrtf_file
            )));
        }

        #[cfg(feature = "bem")]
        {
            self.parse_netcdf_and_convert(&hrtf_file, target_sample_rate)
        }

        #[cfg(not(feature = "bem"))]
        {
            Err(ScannerError::InvalidConfig(
                "BEM support not enabled. Rebuild with --features bem".to_string(),
            ))
        }
    }

    /// Parse NetCDF file and convert to impulse responses
    #[cfg(feature = "bem")]
    fn parse_netcdf_and_convert(
        &self,
        netcdf_path: &Path,
        target_sample_rate: f32,
    ) -> ScannerResult<(Vec<Point3<f32>>, Vec<Vec<Vec<f32>>>)> {
        use netcdf::File as NetCDFFile;

        log::info!("Parsing NetCDF file...");

        // Open NetCDF file
        let file = NetCDFFile::open(netcdf_path)
            .map_err(|e| ScannerError::Io(format!("Failed to open NetCDF file: {}", e)))?;

        // Read source positions
        let source_positions = self.read_source_positions(&file)?;
        log::info!("  Sources: {}", source_positions.len());

        // Read frequency-domain HRTFs
        let frequency_hrtfs = self.read_frequency_hrtfs(&file)?;
        log::info!("  Frequencies: {}", frequency_hrtfs[0][0].len());

        // Convert to time domain using IFFT
        log::info!("Converting to time domain (IFFT)...");
        let impulse_responses = self.convert_to_time_domain(frequency_hrtfs, target_sample_rate)?;

        log::info!("✓ BEM results imported successfully");

        Ok((source_positions, impulse_responses))
    }

    /// Read source positions from NetCDF file
    #[cfg(feature = "bem")]
    fn read_source_positions(&self, file: &netcdf::File) -> ScannerResult<Vec<Point3<f32>>> {
        // MESH2HRTF typically stores source positions in a variable named "sourcePosition"
        // with dimensions [num_sources, 3]

        let var = file
            .variable("sourcePosition")
            .ok_or_else(|| {
                ScannerError::InvalidConfig("sourcePosition variable not found in NetCDF".to_string())
            })?;

        let data: Vec<f32> = var
            .values::<f32, _>(None, None)
            .map_err(|e| ScannerError::Io(format!("Failed to read source positions: {}", e)))?
            .into_iter()
            .collect();

        // Convert flat array to Vec<Point3>
        let num_sources = data.len() / 3;
        let mut positions = Vec::with_capacity(num_sources);

        for i in 0..num_sources {
            let x = data[i * 3] * 100.0; // Convert m to cm
            let y = data[i * 3 + 1] * 100.0;
            let z = data[i * 3 + 2] * 100.0;
            positions.push(Point3::new(x, y, z));
        }

        Ok(positions)
    }

    /// Read frequency-domain HRTFs from NetCDF file
    #[cfg(feature = "bem")]
    fn read_frequency_hrtfs(&self, file: &netcdf::File) -> ScannerResult<Vec<Vec<Vec<(f32, f32)>>>> {
        use num_complex::Complex;

        // MESH2HRTF stores complex transfer functions
        // Typically: "transferFunction" variable with dimensions [num_sources, num_receivers, num_frequencies, 2]
        // Last dimension is [real, imag]

        let var = file
            .variable("transferFunction")
            .ok_or_else(|| {
                ScannerError::InvalidConfig("transferFunction variable not found in NetCDF".to_string())
            })?;

        let shape = var.shape();
        if shape.len() < 4 {
            return Err(ScannerError::InvalidConfig(
                "Invalid transferFunction shape in NetCDF".to_string(),
            ));
        }

        let num_sources = shape[0];
        let num_receivers = shape[1];
        let num_frequencies = shape[2];

        log::info!(
            "  NetCDF shape: {} sources × {} receivers × {} frequencies",
            num_sources,
            num_receivers,
            num_frequencies
        );

        let data: Vec<f32> = var
            .values::<f32, _>(None, None)
            .map_err(|e| ScannerError::Io(format!("Failed to read transfer functions: {}", e)))?
            .into_iter()
            .collect();

        // Convert to nested structure: [source][receiver][frequency] = (real, imag)
        let mut hrtfs = vec![vec![vec![(0.0f32, 0.0f32); num_frequencies]; num_receivers]; num_sources];

        for src in 0..num_sources {
            for rec in 0..num_receivers {
                for freq in 0..num_frequencies {
                    let idx = ((src * num_receivers + rec) * num_frequencies + freq) * 2;
                    let real = data[idx];
                    let imag = data[idx + 1];
                    hrtfs[src][rec][freq] = (real, imag);
                }
            }
        }

        Ok(hrtfs)
    }

    /// Convert frequency-domain HRTFs to time-domain impulse responses using IFFT
    #[cfg(feature = "bem")]
    fn convert_to_time_domain(
        &self,
        frequency_hrtfs: Vec<Vec<Vec<(f32, f32)>>>,
        target_sample_rate: f32,
    ) -> ScannerResult<Vec<Vec<Vec<f32>>>> {
        use num_complex::Complex;
        use rustfft::{FftPlanner, num_complex::Complex as FftComplex};

        let num_sources = frequency_hrtfs.len();
        let num_receivers = frequency_hrtfs[0].len();
        let num_frequencies = frequency_hrtfs[0][0].len();

        // Determine IFFT size (power of 2, typically 2x frequency points for Nyquist)
        let fft_size = (num_frequencies * 2).next_power_of_two();

        log::info!("  IFFT size: {} samples", fft_size);

        // Create IFFT planner
        let mut planner = FftPlanner::new();
        let ifft = planner.plan_fft_inverse(fft_size);

        // Convert each HRTF
        let mut impulse_responses = Vec::with_capacity(num_sources);

        for (src_idx, source_hrtfs) in frequency_hrtfs.iter().enumerate() {
            let mut source_irs = Vec::with_capacity(num_receivers);

            for receiver_hrtf in source_hrtfs {
                // Prepare frequency-domain data
                let mut freq_data: Vec<FftComplex<f32>> = vec![FftComplex::new(0.0, 0.0); fft_size];

                // Copy frequency data (assuming first half is positive frequencies)
                for (i, &(real, imag)) in receiver_hrtf.iter().enumerate() {
                    freq_data[i] = FftComplex::new(real, imag);
                }

                // Mirror for negative frequencies (Hermitian symmetry for real signals)
                for i in 1..num_frequencies {
                    let conj = freq_data[i].conj();
                    freq_data[fft_size - i] = conj;
                }

                // Perform IFFT
                ifft.process(&mut freq_data);

                // Extract real part and normalize
                let normalization = 1.0 / fft_size as f32;
                let ir: Vec<f32> = freq_data
                    .iter()
                    .map(|c| c.re * normalization)
                    .collect();

                // Truncate or pad to desired length (512 samples standard)
                let target_length = 512;
                let mut final_ir = vec![0.0f32; target_length];
                let copy_length = ir.len().min(target_length);
                final_ir[..copy_length].copy_from_slice(&ir[..copy_length]);

                // Apply windowing to reduce artifacts
                self.apply_window(&mut final_ir);

                source_irs.push(final_ir);
            }

            impulse_responses.push(source_irs);

            if (src_idx + 1) % 100 == 0 {
                log::info!("  Processed {}/{} sources", src_idx + 1, num_sources);
            }
        }

        Ok(impulse_responses)
    }

    /// Apply Hann window to reduce IFFT artifacts
    #[cfg(feature = "bem")]
    fn apply_window(&self, ir: &mut [f32]) {
        let n = ir.len();
        for (i, sample) in ir.iter_mut().enumerate() {
            // Hann window: 0.5 * (1 - cos(2π * i / (N-1)))
            let window = 0.5 * (1.0 - (2.0 * std::f32::consts::PI * i as f32 / (n - 1) as f32).cos());
            *sample *= window;
        }
    }
}

/// Helper function to check if BEM solver is available
pub fn is_bem_available() -> bool {
    // Check common installation locations
    let common_paths = [
        "mesh2hrtf",
        "/usr/local/bin/mesh2hrtf",
        "/opt/mesh2hrtf/bin/mesh2hrtf",
    ];

    for path in &common_paths {
        if Path::new(path).exists() {
            return true;
        }
    }

    false
}

/// Get estimated time for BEM simulation
///
/// Returns rough estimate in hours based on:
/// - Number of sources
/// - Number of frequencies
/// - Mesh complexity
pub fn estimate_bem_time(
    num_sources: usize,
    num_frequencies: usize,
    mesh_vertex_count: usize,
) -> f32 {
    // Very rough estimate (actual time varies greatly)
    // Assumes modern workstation with 8+ cores
    let complexity_factor = (mesh_vertex_count as f32 / 1000.0).sqrt();
    let freq_factor = num_frequencies as f32 / 100.0;
    let source_factor = num_sources as f32;

    // Base time per source per frequency: ~1 second
    let total_seconds = complexity_factor * freq_factor * source_factor;

    total_seconds / 3600.0 // Convert to hours
}

