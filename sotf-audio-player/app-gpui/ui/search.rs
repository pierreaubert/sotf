// Macro for sort order handlers - reduces boilerplate for identical patterns
macro_rules! sort_handler {
    ($fn_name:ident, $action:ty, $order:expr) => {
        fn $fn_name(&mut self, _: &$action, _: &mut Window, cx: &mut Context<Self>) {
            self.state.update(cx, |state, _cx| {
                state.app.set_library_sort_order($order);
            });
            cx.notify();
        }
    };
}

// Macro for channel filter handlers - reduces boilerplate for identical patterns
macro_rules! filter_handler {
    ($fn_name:ident, $action:ty, $filter:expr) => {
        fn $fn_name(&mut self, _: &$action, _: &mut Window, cx: &mut Context<Self>) {
            self.state.update(cx, |state, _cx| {
                state.app.set_channel_filter($filter);
            });
            cx.notify();
        }
    };
}

impl PlayerView {
    fn cycle_sort_order(&mut self, _: &CycleSortOrder, _: &mut Window, cx: &mut Context<Self>) {
        self.state.update(cx, |state, _cx| {
            // Block if in text input mode
            if Self::is_text_input_mode(state.app.input_mode) {
                return;
            }
            use crate::app::LibrarySortOrder;
            let next_order = match state.app.library_sort_order {
                LibrarySortOrder::Year => LibrarySortOrder::Genre,
                LibrarySortOrder::Genre => LibrarySortOrder::Artist,
                LibrarySortOrder::Artist => LibrarySortOrder::Album,
                LibrarySortOrder::Album => LibrarySortOrder::Tracks,
                LibrarySortOrder::Tracks => LibrarySortOrder::Composer,
                LibrarySortOrder::Composer => LibrarySortOrder::Popularity,
                LibrarySortOrder::Popularity => LibrarySortOrder::Year,
            };
            state.app.set_library_sort_order(next_order);
        });
        cx.notify();
    }

    // Sort handlers generated by macro
    sort_handler!(set_sort_artist, SetSortArtist, crate::app::LibrarySortOrder::Artist);
    sort_handler!(set_sort_album, SetSortAlbum, crate::app::LibrarySortOrder::Album);
    // Note: Title sorting uses Album sort order (sorts by album title)
    sort_handler!(set_sort_title, SetSortTitle, crate::app::LibrarySortOrder::Album);
    sort_handler!(set_sort_year, SetSortYear, crate::app::LibrarySortOrder::Year);

    fn cycle_channel_filter(
        &mut self,
        _: &CycleChannelFilter,
        _: &mut Window,
        cx: &mut Context<Self>,
    ) {
        self.state.update(cx, |state, _cx| {
            // Block if in text input mode
            if Self::is_text_input_mode(state.app.input_mode) {
                return;
            }
            state.app.cycle_channel_filter();
        });
        cx.notify();
    }

    // Channel filter handlers generated by macro
    filter_handler!(set_filter_all, SetFilterAll, crate::app::ChannelFilter::All);
    filter_handler!(set_filter_mono, SetFilterMono, crate::app::ChannelFilter::Mono);
    filter_handler!(set_filter_stereo, SetFilterStereo, crate::app::ChannelFilter::Stereo);
    filter_handler!(set_filter_surround, SetFilterSurround, crate::app::ChannelFilter::Surround);
    filter_handler!(set_filter_surround71, SetFilterSurround71, crate::app::ChannelFilter::Surround71);
    filter_handler!(set_filter_surround_plus, SetFilterSurroundPlus, crate::app::ChannelFilter::SurroundPlus);
    filter_handler!(set_filter_mixed, SetFilterMixed, crate::app::ChannelFilter::Mixed);

    /// Check if we're in a text input mode where actions should be blocked
    fn is_text_input_mode(input_mode: crate::app::InputMode) -> bool {
        use crate::app::InputMode;
        matches!(
            input_mode,
            InputMode::Search
                | InputMode::AddDirectory
                | InputMode::SavePlugins
                | InputMode::LoadPlugins
                | InputMode::LoadApoFile
                | InputMode::LoadSofaFile
                | InputMode::SpinoramaSpeakerSearch
        )
    }

    fn handle_search_input(&mut self, event: &KeyDownEvent, cx: &mut Context<Self>) {
        log::info!("handle_search_input called with key: {}", event.keystroke.key);
        // Handle text input for search mode
        match event.keystroke.key.as_str() {
            "backspace" => {
                self.state.update(cx, |state, _cx| {
                    state.app.search_query.pop();
                    state.app.selected_album_index = 0;
                    state.app.reset_page();
                });
                cx.notify();
            }
            "escape" => {
                // Exit search mode and clear search
                self.state.update(cx, |state, _cx| {
                    state.app.input_mode = crate::app::InputMode::Normal;
                    state.app.search_query.clear();
                    state.app.selected_album_index = 0;
                    state.app.reset_page();
                });
                cx.notify();
            }
            "enter" => {
                // Exit search mode but keep search results
                self.state.update(cx, |state, _cx| {
                    state.app.input_mode = crate::app::InputMode::Normal;
                });
                cx.notify();
            }
            _ => {
                // Add character to search query
                if let Some(text) = event.keystroke.key_char.as_ref() {
                    self.state.update(cx, |state, _cx| {
                        state.app.search_query.push_str(text);
                        log::info!("Search query updated to: '{}'", state.app.search_query);
                        state.app.selected_album_index = 0;
                        state.app.reset_page();
                    });
                    cx.notify();
                }
            }
        }
    }
}
