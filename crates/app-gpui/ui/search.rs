// Macro for sort order handlers - reduces boilerplate for identical patterns
macro_rules! sort_handler {
    ($fn_name:ident, $action:ty, $order:expr) => {
        fn $fn_name(&mut self, _: &$action, _: &mut Window, cx: &mut Context<Self>) {
            self.state.update(cx, |state, _cx| {
                // Block if in text input mode
                if Self::is_text_input_mode(state.app.ui_state.input_mode) {
                    return;
                }
                state.app.set_library_sort_order($order);
            });
            cx.notify();
        }
    };
}

// Macro for channel filter handlers - reduces boilerplate for identical patterns
macro_rules! filter_handler {
    ($fn_name:ident, $action:ty, $filter:expr) => {
        fn $fn_name(&mut self, _: &$action, _: &mut Window, cx: &mut Context<Self>) {
            self.state.update(cx, |state, _cx| {
                // Block if in text input mode
                if Self::is_text_input_mode(state.app.ui_state.input_mode) {
                    return;
                }
                state.app.set_channel_filter($filter);
            });
            cx.notify();
        }
    };
}

impl PlayerView {
    fn cycle_sort_order(&mut self, _: &CycleSortOrder, _: &mut Window, cx: &mut Context<Self>) {
        self.state.update(cx, |state, _cx| {
            // Block if in text input mode
            if Self::is_text_input_mode(state.app.ui_state.input_mode) {
                return;
            }
            use crate::app::state::library::LibrarySortOrder;
            let next_order = match state.app.library_state.sort_order {
                LibrarySortOrder::Year => LibrarySortOrder::Genre,
                LibrarySortOrder::Genre => LibrarySortOrder::Artist,
                LibrarySortOrder::Artist => LibrarySortOrder::Album,
                LibrarySortOrder::Album => LibrarySortOrder::Tracks,
                LibrarySortOrder::Tracks => LibrarySortOrder::Composer,
                LibrarySortOrder::Composer => LibrarySortOrder::Popularity,
                LibrarySortOrder::Popularity => LibrarySortOrder::Year,
            };
            state.app.set_library_sort_order(next_order);
        });
        cx.notify();
    }

    // Sort handlers generated by macro
    sort_handler!(
        set_sort_artist,
        SetSortArtist,
        crate::app::state::library::LibrarySortOrder::Artist
    );
    sort_handler!(
        set_sort_album,
        SetSortAlbum,
        crate::app::state::library::LibrarySortOrder::Album
    );
    // Note: Title sorting uses Album sort order (sorts by album title)
    sort_handler!(
        set_sort_title,
        SetSortTitle,
        crate::app::state::library::LibrarySortOrder::Album
    );
    sort_handler!(
        set_sort_year,
        SetSortYear,
        crate::app::state::library::LibrarySortOrder::Year
    );

    fn cycle_channel_filter(
        &mut self,
        _: &CycleChannelFilter,
        _: &mut Window,
        cx: &mut Context<Self>,
    ) {
        self.state.update(cx, |state, _cx| {
            // Block if in text input mode
            if Self::is_text_input_mode(state.app.ui_state.input_mode) {
                return;
            }
            state.app.cycle_channel_filter();
        });
        cx.notify();
    }

    fn toggle_favorites_filter(
        &mut self,
        _: &ToggleFavoritesFilter,
        _: &mut Window,
        cx: &mut Context<Self>,
    ) {
        self.state.update(cx, |state, _cx| {
            if Self::is_text_input_mode(state.app.ui_state.input_mode) {
                return;
            }
            state.app.toggle_favorites_filter();
        });
        cx.notify();
    }

    // Channel filter handlers generated by macro
    filter_handler!(
        set_filter_all,
        SetFilterAll,
        crate::app::state::library::ChannelFilter::All
    );
    filter_handler!(
        set_filter_mono,
        SetFilterMono,
        crate::app::state::library::ChannelFilter::Mono
    );
    filter_handler!(
        set_filter_stereo,
        SetFilterStereo,
        crate::app::state::library::ChannelFilter::Stereo
    );
    filter_handler!(
        set_filter_surround,
        SetFilterSurround,
        crate::app::state::library::ChannelFilter::Surround
    );
    filter_handler!(
        set_filter_surround71,
        SetFilterSurround71,
        crate::app::state::library::ChannelFilter::Surround71
    );
    filter_handler!(
        set_filter_surround_plus,
        SetFilterSurroundPlus,
        crate::app::state::library::ChannelFilter::SurroundPlus
    );
    filter_handler!(
        set_filter_mixed,
        SetFilterMixed,
        crate::app::state::library::ChannelFilter::Mixed
    );

    /// Check if we're in a text input mode where actions should be blocked.
    /// Returns true for explicit input modes (search, directory entry, etc.)
    /// and also when a NumberInput component is actively being edited.
    pub(crate) fn is_text_input_mode(input_mode: crate::app::InputMode) -> bool {
        input_mode.is_text_input()
            || gpui_ui_kit::is_number_input_editing()
            || gpui_ui_kit::is_input_editing()
    }
}
