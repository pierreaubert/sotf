//! Form Macro Demo - Binary Application
//!
//! This binary demonstrates the FormField macro in a real application context.
//! Run with: cargo run --bin form-macro-demo -p gpui-ui-kit

use gpui::prelude::*;
use gpui::*;
use gpui_ui_kit::FormField;

/// A settings form component demonstrating the macro
#[derive(FormField, Debug)]
struct UserSettingsForm {
    #[field(required)]
    id: ElementId,
    
    #[field(optional, into)]
    username: Option<SharedString>,
    
    #[field(default = "true")]
    notifications_enabled: bool,
    
    #[field(default = "18")]
    min_age: u32,
    
    #[field(default = "100")]
    max_age: u32,
    
    #[field(default = "1.0")]
    volume: f32,
    
    disabled: bool,
}

/// A login form component
#[derive(FormField, Debug)]
struct LoginForm {
    #[field(required)]
    id: ElementId,
    
    #[field(optional, into)]
    email: Option<SharedString>,
    
    #[field(optional, into)]
    password: Option<SharedString>,
    
    #[field(default = "false")]
    remember_me: bool,
    
    disabled: bool,
}

/// Audio settings form
#[derive(FormField, Debug)]
struct AudioSettingsForm {
    #[field(required)]
    id: ElementId,
    
    #[field(default = "0.75")]
    master_volume: f32,
    
    #[field(default = "true")]
    mute_on_minimize: bool,
    
    #[field(optional, into)]
    output_device: Option<SharedString>,
    
    #[field(default = "48000")]
    sample_rate: u32,
    
    disabled: bool,
}

fn main() {
    println!("╔════════════════════════════════════════════════════════╗");
    println!("║     FormField Macro Demo - Binary Application           ║");
    println!("╚════════════════════════════════════════════════════════╝");
    println!();
    
    // Demo 1: User Settings Form
    println!("📋 User Settings Form:");
    println!("   ─────────────────────────────────────────");
    let settings = UserSettingsForm::new("user-settings")
        .username("johndoe")
        .notifications_enabled(true)
        .min_age(13)
        .max_age(120)
        .volume(0.85)
        .disabled(false);
    
    println!("   ID:          {:?}", settings.id);
    println!("   Username:    {:?}", settings.username);
    println!("   Notifications: {}", settings.notifications_enabled);
    println!("   Age Range:   {} - {}", settings.min_age, settings.max_age);
    println!("   Volume:      {:.0}%", settings.volume * 100.0);
    println!();
    
    // Demo 2: Login Form
    println!("🔐 Login Form:");
    println!("   ─────────────────────────────────────────");
    let login = LoginForm::new("login-form")
        .email("user@example.com")
        .password("********")
        .remember_me(true);
    
    println!("   ID:          {:?}", login.id);
    println!("   Email:       {:?}", login.email);
    println!("   Remember:    {}", login.remember_me);
    println!();
    
    // Demo 3: Audio Settings
    println!("🎵 Audio Settings Form:");
    println!("   ─────────────────────────────────────────");
    let audio = AudioSettingsForm::new("audio-settings")
        .master_volume(0.5)
        .mute_on_minimize(false)
        .output_device("Headphones")
        .sample_rate(44100);
    
    println!("   ID:            {:?}", audio.id);
    println!("   Master Volume: {:.0}%", audio.master_volume * 100.0);
    println!("   Mute on Minimize: {}", audio.mute_on_minimize);
    println!("   Output Device: {:?}", audio.output_device);
    println!("   Sample Rate:   {} Hz", audio.sample_rate);
    println!();
    
    // Demo 4: Minimal construction (defaults only)
    println!("⚡ Minimal Construction (Defaults Only):");
    println!("   ─────────────────────────────────────────");
    let minimal = UserSettingsForm::new("minimal");
    println!("   ID: {:?}", minimal.id);
    println!("   (All other fields use macro-generated defaults)");
    println!();
    
    println!("╔════════════════════════════════════════════════════════╗");
    println!("║  Generated by FormField derive macro - No boilerplate!  ║");
    println!("╚════════════════════════════════════════════════════════╝");
}
