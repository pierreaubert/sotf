/// Cooperative cancellation flag for recording-side capture loops.
///
/// Callers create one with `CancelFlag::default()` (or
/// `Arc::new(AtomicBool::new(false))`) and store it alongside the running
/// task. Setting the flag to `true` from any thread asks the recorder to
/// stop the in-progress playback + capture as soon as the next stability
/// poll fires (worst-case ~50 ms latency). The recorder returns
/// `Err("cancelled")` so callers can distinguish user-cancellation from
/// real failures.
pub type CancelFlag = Arc<AtomicBool>;

/// Canonical error string returned when the recording-side cancel flag
/// is observed during a capture. Stable so UI code can match on it.
pub const CANCELLED_ERR: &str = "cancelled";

#[inline]
fn cancel_requested(cancel: Option<&CancelFlag>) -> bool {
    cancel.is_some_and(|c| c.load(Ordering::Relaxed))
}

/// Signal type for recording
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum SignalType {
    Tone,
    TwoTone,
    Sweep,
    WhiteNoise,
    PinkNoise,
    MNoise,
}

impl SignalType {
    pub fn as_str(&self) -> &'static str {
        match self {
            Self::Tone => "tone",
            Self::TwoTone => "two-tone",
            Self::Sweep => "sweep",
            Self::WhiteNoise => "white-noise",
            Self::PinkNoise => "pink-noise",
            Self::MNoise => "m-noise",
        }
    }
}

impl FromStr for SignalType {
    type Err = String;

    fn from_str(s: &str) -> Result<Self, Self::Err> {
        match s.to_lowercase().as_str() {
            "tone" => Ok(Self::Tone),
            "two-tone" | "twotone" => Ok(Self::TwoTone),
            "sweep" => Ok(Self::Sweep),
            "white-noise" | "white_noise" | "whitenoise" => Ok(Self::WhiteNoise),
            "pink-noise" | "pink_noise" | "pinknoise" => Ok(Self::PinkNoise),
            "m-noise" | "m_noise" | "mnoise" => Ok(Self::MNoise),
            _ => Err(format!("Unknown signal type: {}", s)),
        }
    }
}

/// Parameters for signal generation
#[derive(Debug, Clone)]
pub enum SignalParams {
    Tone {
        freq: f32,
        amp: f32,
    },
    TwoTone {
        freq1: f32,
        amp1: f32,
        freq2: f32,
        amp2: f32,
    },
    Sweep {
        start_freq: f32,
        end_freq: f32,
        amp: f32,
    },
    /// Octave-scaled sweep with pre/post silence windows (GD-Opt v2 §2.7).
    ///
    /// The sweep itself is generated by [`gen_log_sweep_octave_scaled`]; silence
    /// windows are prepended and appended so the noise floor and room decay can
    /// be measured from the same recording file.
    OctaveSweep {
        start_freq: f32,
        end_freq: f32,
        amp: f32,
        /// Seconds per octave below 100 Hz (default 3.0, clamped [1.0..10.0]).
        bass_octave_duration_s: f32,
        /// Silence window before the sweep in seconds (default 2.0).
        pre_silence_s: f32,
        /// Silence window after the sweep in seconds (default ≈ RT60 + 1.0).
        post_silence_s: f32,
    },
    Noise {
        amp: f32,
    },
}

/// Build an octave-scaled sweep surrounded by silence windows.
///
/// Returns `[pre_silence | sweep | post_silence]` as a flat `Vec<f32>`.
/// This is the core of the GD-Opt v2 Phase GD-1b signal path.
fn build_octave_sweep_with_silence(
    start_freq: f32,
    end_freq: f32,
    amp: f32,
    bass_octave_duration_s: f32,
    pre_silence_s: f32,
    post_silence_s: f32,
    sample_rate: u32,
) -> Vec<f32> {
    // Clamp bass duration per the design contract.
    let bass_dur = bass_octave_duration_s.clamp(1.0, 10.0);

    // The minimum total sweep duration is one full second so the upper octaves
    // remain usable even with a very narrow frequency range.
    let min_sweep_dur = 1.0_f32;

    let sweep = gen_log_sweep_octave_scaled(
        start_freq, end_freq, amp, sample_rate, bass_dur, min_sweep_dur,
    );

    let pre_n  = (pre_silence_s.max(0.0)  * sample_rate as f32).round() as usize;
    let post_n = (post_silence_s.max(0.0) * sample_rate as f32).round() as usize;

    let total = pre_n + sweep.len() + post_n;
    let mut out = vec![0.0_f32; total];
    out[pre_n..pre_n + sweep.len()].copy_from_slice(&sweep);
    out
}

/// Generate a signal based on parameters
pub fn generate_signal(
    signal_type: SignalType,
    params: &SignalParams,
    duration: f32,
    sample_rate: u32,
) -> Result<Vec<f32>, String> {
    let signal = match (signal_type, params) {
        (SignalType::Tone, SignalParams::Tone { freq, amp }) => {
            gen_tone(*freq, *amp, sample_rate, duration)
        }
        (
            SignalType::TwoTone,
            SignalParams::TwoTone {
                freq1,
                amp1,
                freq2,
                amp2,
            },
        ) => gen_two_tone(*freq1, *amp1, *freq2, *amp2, sample_rate, duration),
        (
            SignalType::Sweep,
            SignalParams::Sweep {
                start_freq,
                end_freq,
                amp,
            },
        ) => gen_log_sweep(*start_freq, *end_freq, *amp, sample_rate, duration),
        // OctaveSweep is self-timed: the `duration` argument is ignored because
        // the total length is determined by the octave budget and silence windows.
        (
            SignalType::Sweep,
            SignalParams::OctaveSweep {
                start_freq,
                end_freq,
                amp,
                bass_octave_duration_s,
                pre_silence_s,
                post_silence_s,
            },
        ) => build_octave_sweep_with_silence(
            *start_freq,
            *end_freq,
            *amp,
            *bass_octave_duration_s,
            *pre_silence_s,
            *post_silence_s,
            sample_rate,
        ),
        (SignalType::WhiteNoise, SignalParams::Noise { amp }) => {
            gen_white_noise(*amp, sample_rate, duration)
        }
        (SignalType::PinkNoise, SignalParams::Noise { amp }) => {
            gen_pink_noise(*amp, sample_rate, duration)
        }
        (SignalType::MNoise, SignalParams::Noise { amp }) => {
            gen_m_noise(*amp, sample_rate, duration)
        }
        _ => {
            return Err(format!(
                "Signal type {:?} does not match parameters {:?}",
                signal_type, params
            ));
        }
    };

    Ok(signal)
}

/// Build `SignalParams` for the sweep path used by `record_and_analyze`.
///
/// When `RecordingConfiguration` carries the GD-Opt v2 fields, returns an
/// [`SignalParams::OctaveSweep`]; otherwise falls back to legacy
/// [`SignalParams::Sweep`] so existing callers are not affected.
pub fn sweep_params_from_config(
    start_freq: f32,
    end_freq: f32,
    amp: f32,
    bass_octave_duration_s: Option<f32>,
    pre_silence_s: Option<f32>,
    post_silence_s: Option<f32>,
) -> SignalParams {
    match bass_octave_duration_s {
        Some(bass_dur) => SignalParams::OctaveSweep {
            start_freq,
            end_freq,
            amp,
            bass_octave_duration_s: bass_dur.clamp(1.0, 10.0),
            pre_silence_s: pre_silence_s.unwrap_or(2.0).max(0.0),
            post_silence_s: post_silence_s.unwrap_or(2.0).max(0.0),
        },
        None => SignalParams::Sweep {
            start_freq,
            end_freq,
            amp,
        },
    }
}

/// Prepare a signal for playback with fades and padding
pub fn prepare_signal(signal: Vec<f32>, sample_rate: u32) -> Vec<f32> {
    const FADE_MS: f32 = 20.0;
    const PADDING_MS: f32 = 250.0;

    prepare_signal_for_playback(signal, sample_rate, FADE_MS, PADDING_MS)
}

/// Write signal to a temporary WAV file
pub fn write_temp_wav(
    signal: &[f32],
    sample_rate: u32,
    channels: u16,
) -> Result<NamedTempFile, String> {
    let temp_file = NamedTempFile::with_suffix(".wav")
        .map_err(|e| format!("Failed to create temp file: {}", e))?;

    write_wav_file(temp_file.path(), signal, sample_rate, channels)?;

    Ok(temp_file)
}

/// Write signal to a WAV file
pub fn write_wav_file(
    path: &Path,
    signal: &[f32],
    sample_rate: u32,
    channels: u16,
) -> Result<(), String> {
    let spec = WavSpec {
        channels,
        sample_rate,
        bits_per_sample: 32,
        sample_format: SampleFormat::Float,
    };

    let mut writer =
        WavWriter::create(path, spec).map_err(|e| format!("Failed to create WAV writer: {}", e))?;

    for &sample in signal {
        writer
            .write_sample(sample)
            .map_err(|e| format!("Failed to write sample: {}", e))?;
    }

    writer
        .finalize()
        .map_err(|e| format!("Failed to finalize WAV file: {}", e))?;

    Ok(())
}

/// Generate output filenames for a recording with both send and record channels
pub fn generate_output_filenames_stereo(
    name_prefix: Option<&str>,
    signal_type: SignalType,
    send_channel: u16,
    record_channel: u16,
    sample_rate: u32,
) -> (PathBuf, PathBuf) {
    let base_name = if let Some(prefix) = name_prefix {
        format!(
            "{}_{}_send{}_rec{}_{}",
            prefix,
            signal_type.as_str(),
            send_channel,
            record_channel,
            sample_rate
        )
    } else {
        format!(
            "{}_send{}_rec{}_{}",
            signal_type.as_str(),
            send_channel,
            record_channel,
            sample_rate
        )
    };

    let wav_path = PathBuf::from(format!("{}.wav", base_name));
    let csv_path = PathBuf::from(format!("{}.csv", base_name));

    (wav_path, csv_path)
}

