# MAIN
# -----------------------------------------------------------------------

main() {
    log_phase "SotF Release Build v${VERSION}"

    if $DRY_RUN; then
        log_warning "DRY RUN — no actions will be taken"
    fi

    preflight

    if ! $POST_ONLY; then
        build_macos
        build_linux
        build_windows
    else
        log_info "Post-only mode — skipping builds"
    fi

    post_build
    print_summary
}

