# Track build results
declare -a BUILD_RESULTS=()
record_result() {
    BUILD_RESULTS+=("$1")
}

# Time a phase
phase_start_time=0
start_timer() { phase_start_time=$(date +%s); }
elapsed() {
    local now
    now=$(date +%s)
    local diff=$((now - phase_start_time))
    printf '%dm%02ds' $((diff / 60)) $((diff % 60))
}

# -----------------------------------------------------------------------
# PHASE 0: PREFLIGHT CHECKS
# -----------------------------------------------------------------------

preflight() {
    log_phase "Phase 0: Preflight Checks"

    log_step "Version: v${VERSION}"
    log_step "Dist dir: ${DIST_DIR}"

    # Sync auxiliary version-pinned files (AppxManifest.xml, site/package.json)
    # to the workspace Cargo.toml version BEFORE any remote rsync, so the
    # Windows builder picks up the correct manifest.
    log_step "Syncing version-pinned files to v${VERSION}..."
    if $DRY_RUN; then
        log_dry "./scripts/sync-version.sh"
    else
        if ! "$SCRIPT_DIR/sync-version.sh"; then
            log_error "Version sync failed"
            exit 1
        fi
    fi

    # Check local tools
    local missing=()
    command -v cargo &>/dev/null || missing+=("cargo")
    command -v just &>/dev/null  || missing+=("just")
    command -v rsync &>/dev/null || missing+=("rsync")

    if ! $SKIP_SIGN; then
        command -v cosign &>/dev/null || missing+=("cosign")
    fi

    if [ ${#missing[@]} -gt 0 ]; then
        log_error "Missing required tools: ${missing[*]}"
        exit 1
    fi
    log_success "Local tools OK"

    # Check git is clean
    if [ -n "$(git -C "$PROJECT_ROOT" status --porcelain)" ]; then
        log_warning "Working directory has uncommitted changes"
        log_info "Builds will use the current working tree state"
    fi

    # Check SSH connectivity
    if ! $SKIP_LINUX && ! $POST_ONLY; then
        log_step "Testing SSH to Linux: ${LINUX_HOST:-<not configured>}"
        if [ -z "${LINUX_HOST:-}" ]; then
            log_error "LINUX_HOST not configured in $CONFIG_FILE"
            exit 1
        fi
        if $DRY_RUN; then
            log_dry "ssh ${LINUX_HOST} echo ok"
        else
            if ssh_cmd "$LINUX_HOST" "${LINUX_PORT:-22}" "${LINUX_SSH_KEY:-}" "echo ok" &>/dev/null; then
                log_success "Linux SSH OK"
            else
                log_error "Cannot SSH to $LINUX_HOST"
                exit 1
            fi
        fi
    fi

    if ! $SKIP_WINDOWS && ! $POST_ONLY; then
        log_step "Testing SSH to Windows: ${WINDOWS_HOST:-<not configured>}"
        if [ -z "${WINDOWS_HOST:-}" ]; then
            log_error "WINDOWS_HOST not configured in $CONFIG_FILE"
            exit 1
        fi
        if $DRY_RUN; then
            log_dry "ssh ${WINDOWS_HOST} echo ok"
        else
            if ssh_cmd "$WINDOWS_HOST" "${WINDOWS_PORT:-22}" "${WINDOWS_SSH_KEY:-}" "echo ok" &>/dev/null; then
                log_success "Windows SSH OK"
            else
                log_error "Cannot SSH to $WINDOWS_HOST"
                exit 1
            fi
        fi
    fi

    mkdir -p "$DIST_DIR"
    log_success "Preflight complete"
}

# -----------------------------------------------------------------------
# PHASE 1: macOS BUILDS (local)
# -----------------------------------------------------------------------

build_macos() {
    if $SKIP_MACOS; then
        log_info "Skipping macOS builds (--skip-macos)"
        return
    fi

    log_phase "Phase 1: macOS Builds (local)"
    start_timer

    cd "$PROJECT_ROOT"

    # We deliberately do NOT use `just cross-macos-{arm64,x86}` here. Those
    # recipes historically rebuilt the GPUI binary with
    # `RUSTFLAGS="-C target-feature=+crt-static"` into `./target-static/` before
    # wrapping it in a DMG. The static binary cannot be signed/notarized
    # cleanly, so this pipeline builds the dynamically-linked binary first and
    # then asks the DMG script to package that exact binary.

    # --- macOS ARM64 ---
    log_step "Building macOS ARM64 (dynamic) ..."
    if $DRY_RUN; then
        log_dry "cargo build --release --target aarch64-apple-darwin (sotf-tui, sotf-desktop)"
        log_dry "./scripts/build-dmg-sotf.sh --arch arm64 --binary target/aarch64-apple-darwin/release/sotf-desktop"
    else
        rustup target add aarch64-apple-darwin 2>/dev/null || true
        cargo build --release --target aarch64-apple-darwin -p sotf-tui --features hal,onnx
        cargo build --release --target aarch64-apple-darwin -p sotf-gpui --features hal,onnx
        mkdir -p "$DIST_DIR"
        cp "target/aarch64-apple-darwin/release/sotf-tui"     "$DIST_DIR/sotf-tui-${VERSION}-macos-arm64"
        cp "target/aarch64-apple-darwin/release/sotf-desktop" "$DIST_DIR/sotf-desktop-${VERSION}-macos-arm64"
        record_result "macOS ARM64: OK"
        if ./scripts/build-dmg-sotf.sh --arch arm64 --binary "target/aarch64-apple-darwin/release/sotf-desktop"; then
            record_result "macOS ARM64 DMG: OK"
        else
            log_error "macOS ARM64 DMG packaging failed"
            record_result "macOS ARM64 DMG: FAILED"
            exit 1
        fi
    fi

    # --- macOS x86_64 ---
    log_step "Building macOS x86_64 (dynamic) ..."
    if $DRY_RUN; then
        log_dry "cargo build --release --target x86_64-apple-darwin (sotf-tui, sotf-desktop)"
        log_dry "./scripts/build-dmg-sotf.sh --arch x86_64 --binary target/x86_64-apple-darwin/release/sotf-desktop"
    else
        rustup target add x86_64-apple-darwin 2>/dev/null || true
        cargo build --release --target x86_64-apple-darwin -p sotf-tui --features hal
        cargo build --release --target x86_64-apple-darwin -p sotf-gpui --features hal
        mkdir -p "$DIST_DIR"
        cp "target/x86_64-apple-darwin/release/sotf-tui"     "$DIST_DIR/sotf-tui-${VERSION}-macos-x86_64"
        cp "target/x86_64-apple-darwin/release/sotf-desktop" "$DIST_DIR/sotf-desktop-${VERSION}-macos-x86_64"
        record_result "macOS x86_64: OK"
        if ./scripts/build-dmg-sotf.sh --arch x86_64 --binary "target/x86_64-apple-darwin/release/sotf-desktop"; then
            record_result "macOS x86_64 DMG: OK"
        else
            log_error "macOS x86_64 DMG packaging failed"
            record_result "macOS x86_64 DMG: FAILED"
            exit 1
        fi
    fi

    # --- macOS Systemwide pkg ---
    log_step "Building macOS Systemwide pkg..."
    if $DRY_RUN; then
        log_dry "./scripts/build-systemwide.sh"
    else
        ./scripts/build-systemwide.sh
        record_result "macOS Systemwide pkg: OK"
    fi

    # --- Sign macOS artifacts ---
    if ! $SKIP_SIGN && [ -n "${DEVELOPER_ID:-}" ]; then
        log_step "Signing macOS artifacts..."
        if $DRY_RUN; then
            log_dry "./scripts/sign-macos.sh --notarize"
        else
            export DEVELOPER_ID
            export INSTALLER_DEVELOPER_ID="${INSTALLER_DEVELOPER_ID:-}"
            export APPLE_ID="${APPLE_ID:-}"

            ./scripts/sign-macos.sh
            log_success "macOS code signing complete"

            if [ -n "${APPLE_ID:-}" ]; then
                log_step "Notarizing macOS artifacts..."
                ./scripts/sign-macos.sh --notarize
                log_success "macOS notarization complete"
            else
                log_warning "APPLE_ID not set, skipping notarization"
            fi
            record_result "macOS signing: OK"
        fi
    elif ! $SKIP_SIGN; then
        log_warning "DEVELOPER_ID not set, skipping macOS signing"
        record_result "macOS signing: SKIPPED (no DEVELOPER_ID)"
    fi

    log_success "macOS builds complete ($(elapsed))"
}

